 const full=await page.locator('.chat-drawer').boundingBox();
 assert.equal(full.width,1440,'agent list opens a full-screen conversation');
 assert.equal(full.y,0);
 assert.equal(await page.locator('#topbar').isVisible(),false);
 assert.equal((await page.locator('.pilot-panel > header').boundingBox()).height,80);
 assert.equal(await page.locator('.pilot-panel .resize-controls').count(),0);
 assert.equal(full.x,0,'chat does not reserve sidebar space');
 assert.equal(await page.getByRole('navigation',{name:'Agent navigation'}).count(),0);
 assert.equal(await page.locator('.pilot-panel .note-history').count(),0);
 await page.locator('.pilot-panel [contenteditable=true]').evaluate(el=>el.blur());
 const route=page.url();
 await page.keyboard.press('h');await page.keyboard.press('l');
 assert.equal(page.url(),route,'H/L no longer navigate between agents or leave the conversation');
 await page.keyboard.press('r');
 await page.getByRole('textbox',{name:'Chat title',exact:true}).fill('Renamed Atlas');
 await page.keyboard.press('Enter');
 await page.getByRole('button',{name:'Rename chat',exact:true}).waitFor();
 assert((await page.locator('.chat-title').textContent()).includes('Renamed Atlas'));
 await page.getByRole('button',{name:'Rename chat',exact:true}).click();
 await page.getByRole('textbox',{name:'Chat title',exact:true}).fill('Cancel this');
 await page.keyboard.press('Escape');
 assert((await page.locator('.chat-title').textContent()).includes('Renamed Atlas'));
 const editor = page.locator('.pilot-panel [contenteditable=true]');
 assert.equal(await editor.getAttribute('data-input-hint'),null);
 assert.equal(await page.locator('.composer-talk').count(),0);
 assert.equal(await editor.evaluate(el=>el===document.activeElement),true,'composer focuses after opening and renaming');
 // Native macOS text editing must reach the browser without app cancellation.
 const intercepted = await editor.evaluate(el=>{
   return ['k','e','d'].map(key=>{
     const event=new KeyboardEvent('keydown',{key,ctrlKey:true,bubbles:true,cancelable:true});
     el.dispatchEvent(event); return event.defaultPrevented;
   });
 });
 assert.deepEqual(intercepted,[false,false,false]);
 await page.keyboard.press('Meta+k');
 assert.equal(await editor.evaluate(el=>el===document.activeElement),true,'Cmd-K keeps focus in composer');
 assert.equal(await page.getByRole('combobox',{name:'Search the vault'}).count(),0);
 await editor.fill('alpha beta');
 await page.keyboard.press('Control+a');
 await page.keyboard.press('Control+d');
 await page.keyboard.press('Control+e');
 await page.keyboard.type('!');
 if(process.platform==='darwin') assert.equal(await editor.textContent(),'lpha beta!');
 await page.keyboard.press('Control+a');
 await page.keyboard.press('Control+k');
 if(process.platform==='darwin') assert.equal(await editor.textContent(),'');
 await editor.fill('Keep this draft');
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>location.hash==='#/home' && document.documentElement.dataset.sidebarWorkbench==='closed');
 assert.equal(await page.locator('.pilots-pane').count(),0);
 assert.equal(await page.locator('.workspace-menu').count(),0);
 assert.equal(await page.locator('html').getAttribute('data-sidebar-hidden'),'true');
 await page.keyboard.press('a');
 await page.locator('.pilot-row').filter({hasText:'Renamed Atlas'}).click();
