 assert.equal(await page.locator('.pilots-pane').count(),0);
 await page.keyboard.press('a');
 await page.locator('.pilot-row').first().waitFor();
 await page.evaluate(async()=>{
   const later=Date.now()+13*60*60*1000;
   Date.now=()=>later;
   const {refreshChats}=await import('/src/lib/pilotChat.svelte.ts');
   await refreshChats();
 });
 assert.equal(await page.locator('.pilot-row').count(),5,'time alone never removes an agent');
