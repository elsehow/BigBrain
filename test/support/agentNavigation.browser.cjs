 await page.waitForFunction(()=>document.querySelectorAll('.pilot-row').length===5);
 const names=await page.locator('.pilot-row .row-heading strong').allTextContents();
 assert.equal(names.length,5);
 assert(names.includes('Atlas design review'),'recently active ingested agent stays visible');
 assert(names.includes('Earlier project review') && names.includes('Completed Atlas review'),'all sessions remain, including archived history');
 await page.locator('.pilot-row').filter({hasText:'Atlas planning'}).click();
